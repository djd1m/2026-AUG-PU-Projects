#!/usr/bin/env bash
# Маршрутизатор сложности — исполняемая часть правила .claude/rules/complexity-router.md.
#
# ЗАЧЕМ ОН СУЩЕСТВУЕТ. Правило лежит на слое 2 (всегда загружаемое) и работает ровно до тех
# пор, пока его кто-то читает и честно себе отвечает. Признаки при этом в большинстве своём
# МЕХАНИЧЕСКИЕ: «трогает ли миграции», «появляется ли GRANT», «есть ли новый внешний вызов» —
# всё это видно в диффе. Значит их место на слое 1, а не в памяти исполнителя.
#
# ЧЕГО ОН НЕ ДЕЛАЕТ, и это важнее того, что делает. Он смотрит на ИЗМЕНЁННЫЕ ФАЙЛЫ, то есть
# отвечает постфактум либо по заранее названному списку. Он не читает постановку и не знает
# намерения: «фича трогает деньги» он видит только если слово уже появилось в коде. Поэтому его
# вердикт — НИЖНЯЯ ГРАНИЦА тира, а не окончательный ответ. Поднять тир человек может всегда,
# опустить — только осознанно и с записью в коммит.
#
# Коды возврата — три, и третий главный:
#   0  тир определён
#   1  тир определён и это L или XL — то есть требуется полный цикл, а не «просто сделать»
#   2  ПРОВЕРКА НЕ ВЫПОЛНЕНА: нечего анализировать (нет изменений и не передан список)
#
# Использование:
#   bash scripts/complexity-router.sh                    # по незакоммиченным изменениям
#   bash scripts/complexity-router.sh --staged           # по индексу
#   bash scripts/complexity-router.sh f1.ts f2.sql ...   # по явному списку

set -uo pipefail
cd "$(git rev-parse --show-toplevel 2>/dev/null || echo .)" || exit 2

MODE="worktree"
FILES=""
case "${1:-}" in
  --staged) MODE="staged"; shift ;;
  --help|-h) sed -n '2,25p' "$0"; exit 0 ;;
esac

if [ $# -gt 0 ]; then
  MODE="explicit"
  FILES=$(printf '%s\n' "$@")
elif [ "$MODE" = "staged" ]; then
  FILES=$(git diff --cached --name-only)
else
  FILES=$(git status --porcelain | awk '{print $NF}')
fi

FILES=$(printf '%s\n' "$FILES" | grep -v '^$' || true)

# Самоисключение. Детектор содержит те самые строки, которые ищет: файл, ищущий слово
# «yookassa», это слово содержит. Без исключения роутер объявляет XL самому себе — тот же
# класс «форма вместо смысла», доведённый до рекурсии. Инструмент не классифицирует себя.
SELF="scripts/complexity-router.sh"
SCAN=$(printf '%s\n' "$FILES" | grep -vF "$SELF" || true)

if [ -z "$FILES" ]; then
  echo "❌ анализировать нечего: нет изменений и не передан список файлов" >&2
  echo "   проверка НЕ ВЫПОЛНЕНА — это не «тир T», это отсутствие входных данных" >&2
  exit 2
fi

COUNT=$(printf '%s\n' "$FILES" | wc -l | tr -d ' ')

# ── Документы отсекаются ПЕРВЫМИ, до чтения содержимого.
#
# Иначе правило, ОПИСЫВАЮЩЕЕ признак, само его и вызывает: файл про кэш содержит слово «кэш»,
# заявка про гранты — слово GRANT, и роутер объявляет тир М документу, который ничего не
# делает. Это третий за прогон случай одного класса — «проверка ловит форму, а не смысл»;
# лечится тем, что проза не сканируется как код ПО ПОСТРОЕНИЮ, а не оговорками в регэкспах.
if ! printf '%s\n' "$FILES" | grep -qvE '\.(md|txt|json|ya?ml|env\.example)$'; then
  echo "── маршрутизатор сложности"
  echo "   файлов в работе: $COUNT · режим: $MODE"
  echo "   ТИР: T"
  echo "   сработавшие признаки:"
  echo "     · только документы и конфигурация — содержимое не сканируется"
  echo "   → просто сделать"
  exit 0
fi

# Содержимое берётся из диффа, а не из файлов целиком: признак — то, что ДОБАВЛЕНО этой
# работой. Существующее слово «payment» в чужом файле про эту фичу не говорит ничего.
if [ "$MODE" = "explicit" ]; then
  ADDED=$([ -n "$SCAN" ] && cat -- $SCAN 2>/dev/null || true)
elif [ "$MODE" = "staged" ]; then
  ADDED=$(git diff --cached -U0 -- $SCAN 2>/dev/null | grep '^+' | grep -v '^+++' || true)
else
  ADDED=$(git diff -U0 -- $SCAN 2>/dev/null | grep '^+' | grep -v '^+++' || true)
  UNTRACKED=$(git ls-files --others --exclude-standard | grep -vF "$SELF" || true)
  [ -n "$UNTRACKED" ] && ADDED="$ADDED
$(cat -- $UNTRACKED 2>/dev/null || true)"
fi

TIER="S"
REASONS=""
note() { REASONS="${REASONS}  · ${1}"$'\n'; }
raise() { # raise <тир> <причина>
  case "$1" in
    XL) TIER="XL" ;;
    L)  [ "$TIER" = "XL" ] || TIER="L" ;;
    M)  case "$TIER" in XL|L) ;; *) TIER="M" ;; esac ;;
  esac
  note "$2"
}

# ── XL: деньги и необратимость
# Признак ищется по ИДЕНТИФИКАТОРАМ денежной машинерии, а не по словам. Первая редакция
# ловила «тариф» и «оплат» в тексте интерфейса и объявляла XL форме на сто строк — ложное
# красное, которое отключают вместе с настоящим (PR-030). Слова про деньги в подписи кнопки
# деньгами не распоряжаются; ими распоряжается вызов провайдера и запись в таблицу платежей.
echo "$ADDED" | grep -qE 'yookassa|YOOKASSA|checkout_session|payment_event|webhook_events|commissions|PAYMENTS_STUB|PRICE_[A-Z_]+|api\.stripe|/v3/payments' \
  && raise XL "деньги: обращение к платёжному провайдеру или его таблицам"
echo "$FILES" | grep -qE '/(payment|billing|checkout|webhooks?)[./-]' \
  && raise XL "файл денежного тракта в списке изменений"

# ── L: схема, права, публичный путь, внешний вызов, вторая граница
echo "$FILES" | grep -qE 'migrations/.*\.sql$' \
  && raise L "миграция схемы"
echo "$ADDED" | grep -qiE '\b(grant|revoke|create role|create policy|row level security)\b' \
  && raise L "права СУБД: GRANT, роль или политика"
# ВНЕШНИЙ вызов — это обращение к ЧУЖОМУ хосту, а не любой fetch. Первая редакция ловила
# fetch('/api/...') к нашему же маршруту и адрес-подсказку в поле ввода формы, объявляя L
# работе, которая не выходит за пределы приложения. Признак сузился до двух форм: вызов с
# абсолютным адресом и имя известного провайдера в коде.
echo "$ADDED" | grep -qE "fetch\(['\"\`]https?://|api\.(openai|telegram|yookassa|stripe|resend)\.(com|org|ru)" \
  && raise L "новый внешний вызов: обращение к чужому хосту"
CONTAINERS=$(printf '%s\n' "$FILES" | grep -oE '^(apps|services)/[a-z0-9-]+' | sort -u | wc -l | tr -d ' ')
[ "${CONTAINERS:-0}" -ge 2 ] \
  && raise L "работа пересекает границу контейнеров (затронуто: $CONTAINERS)"

# ── M: изменён существующий публичный контракт или поведение
echo "$FILES" | grep -qE '(api|routes?)/.*\.(ts|tsx|js)$' \
  && raise M "затронут публичный маршрут"
# По КОНСТРУКЦИЯМ, не по словам: «повтор» и «кэш» встречаются в любом комментарии, который
# честно объясняет, почему их здесь нет.
echo "$ADDED" | grep -qE 'setTimeout\(|AbortSignal\.timeout|Cache-Control|revalidate|MAX_ATTEMPTS|_TTL|TTL_MS|maxAge' \
  && raise M "затронуты кэш, повторы или таймауты (по конструкциям кода)"

echo "── маршрутизатор сложности"
echo "   файлов в работе: $COUNT · режим: $MODE"
echo "   ТИР: $TIER"
[ -n "$REASONS" ] && { echo "   сработавшие признаки:"; printf '%s' "$REASONS"; }

case "$TIER" in
  T)  echo "   → просто сделать" ;;
  S)  echo "   → напрямую: код + тест + мутация" ;;
  M)  echo "   → напрямую + обязательный набор: страж с мутацией, конкурентный тест при"
      echo "     разделяемом ресурсе, перекрёстное чтение документов, ПОЛНЫЙ прогон всех наборов" ;;
  L)  echo "   → /feature полным циклом: PLAN → VALIDATE → IMPLEMENT → REVIEW" ;;
  XL) echo "   → /feature полным циклом + ОСТАНОВКА на плане до одобрения владельца" ;;
esac

echo
echo "   Ограничение: вердикт — НИЖНЯЯ граница. Скрипт видит изменённые файлы, а не замысел;"
echo "   признак «деньги» он замечает, только когда слово уже появилось в коде. Поднять тир"
echo "   можно всегда, опустить — осознанно и строкой в коммите."

case "$TIER" in
  L|XL) exit 1 ;;
  *)    exit 0 ;;
esac
