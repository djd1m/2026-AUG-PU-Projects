#!/usr/bin/env bash
# Локальные артефакты, которые апстрим мог уже заменить.
#
# Запускать ПОСЛЕ каждого `npx @dzhechkov/p-replicator update`.
#
# Задача не «найти дубли автоматически» — это не машинно разрешимо. Задача —
# предъявить человеку список того, что он однажды написал взамен отсутствующего
# в пакете, чтобы решение «оставить или снять» принималось СОЗНАТЕЛЬНО, а не
# забывалось. Два места с одним правилом расходятся молча и стоят дороже, чем
# отсутствие правила: заслужено docker-ports.md, где апстрим выпустил лучшую
# версию, а локальная чуть не была возвращена поверх неё.
#
# Коды: 0 — все помеченные артефакты на месте; 1 — метка есть, файла нет;
#       2 — проверка не выполнена (нет манифеста пакета)

set -uo pipefail
cd "$(dirname "$0")/.."
FAIL=0

MANIFEST=.p-replicator.json
if [ ! -f "$MANIFEST" ]; then
  echo "❌ нет $MANIFEST — проверка НЕ выполнена" >&2
  exit 2
fi
VERSION=$(python3 -c "import json;print(json.load(open('$MANIFEST'))['version'])" 2>/dev/null || echo "?")

echo "== Локальные артефакты против пакета $VERSION =="
echo

# Файлы, несущие метку ЗАМЕЩЕНИЕ
FOUND=0
while IFS= read -r f; do
  FOUND=$((FOUND+1))
  PR=$(grep -m1 'ЗАМЕЩЕНИЕ: отслеживает' "$f" | sed 's/.*отслеживает //')
  ST=$(grep -m1 'Статус апстрима:' "$f" | sed 's/.*Статус апстрима: //')
  printf '  📌 %s\n     заявка: %s\n     статус: %s\n\n' "$f" "$PR" "$ST"
done < <(grep -rl 'ЗАМЕЩЕНИЕ: отслеживает' \
           .claude scripts projects/*/scripts 2>/dev/null \
         | grep -v 'check-superseded.sh' | sort)   # сам скрипт содержит искомую строку

if [ "$FOUND" -eq 0 ]; then
  echo "  ⚠ ни одного помеченного артефакта не найдено — метки потерялись при обновлении?"
  FAIL=1
fi

echo "== Что проверить руками =="
echo "  1. Появился ли в пакете хук/правило, покрывающее заявку из списка выше?"
echo "     ls .claude/hooks/ .claude/rules/"
echo "  2. Если появился — локальный артефакт УДАЛИТЬ либо урезать до того,"
echo "     чего в пакете нет. Не оставлять оба."
echo "  3. Если апстрим отказался включать (так с check-port-conflicts.sh) —"
echo "     отметить артефакт ПОСТОЯННЫМ в его же метке."
echo
echo "  Вендорные файлы НЕ ПРАВИТЬ: обновление их перезапишет. Локальная политика"
echo "  живёт отдельными файлами — так port-conflicts-local.md пережил 1.9.0."

exit $FAIL
