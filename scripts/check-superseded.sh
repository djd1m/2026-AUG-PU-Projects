#!/usr/bin/env bash
# Локальные артефакты, которые апстрим мог уже заменить.
#
# Запускать ПОСЛЕ каждого `npx @dzhechkov/p-replicator update`.
#
# Задача не «найти дубли автоматически» — это не машинно разрешимо. Задача —
# предъявить человеку ВСЁ, что он однажды написал взамен отсутствующего в пакете,
# чтобы решение «оставить или снять» принималось СОЗНАТЕЛЬНО, а не забывалось.
# Два места с одним правилом расходятся молча и стоят дороже отсутствия правила:
# заслужено docker-ports.md, где апстрим выпустил лучшую версию, а локальная чуть
# не была возвращена поверх неё.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧИНЕНО 2026-09-01. Прежняя редакция печатала ТОЛЬКО файлы с меткой
# «ЗАМЕЩЕНИЕ: отслеживает». Файл без метки для неё не существовал.
#
# Как это выстрелило: обновление 1.10.3 → 1.12.0 принесло honest-configuration.md,
# накрывающее наши fail-closed-defaults.md (88 строк) и silent-fallbacks.md (94),
# и swarm-file-evidence.md, реализующее нашу заявку PR-025. Метки не было ни у
# одного из трёх — страж промолчал обо всех и напечатал семь посторонних.
#
# То есть он отвечал не на вопрос «что дублируется», а на вопрос «что мне велели
# отслеживать». Это ровно класс guard-must-be-able-to-fail.md: проверка, зелёная
# по построению. Теперь перечисляются ВСЕ локальные артефакты; отсутствие метки —
# отдельная категория и причина ненулевого кода возврата, а не тишина.
# ─────────────────────────────────────────────────────────────────────────────
#
# Коды: 0 — все локальные артефакты помечены и на месте
#       1 — есть непомеченные, либо метка есть, а файла нет
#       2 — проверка НЕ ВЫПОЛНЕНА (нет манифеста пакета или он нечитаем)

set -uo pipefail
cd "$(dirname "$0")/.."
FAIL=0
SELF='check-superseded.sh'

MANIFEST=.p-replicator.json
if [ ! -f "$MANIFEST" ]; then
  echo "❌ нет $MANIFEST — проверка НЕ выполнена" >&2
  exit 2
fi

# Список вендорных файлов берётся ИЗ МАНИФЕСТА, а не угадывается по именам.
# Нечитаемый манифест — код 2, а не «локальных артефактов не найдено»:
# проверка, отвечающая «чисто» на непрочитанном входе, хуже её отсутствия.
VENDOR=$(python3 - "$MANIFEST" <<'PY' 2>/dev/null
import json,sys
d=json.load(open(sys.argv[1]))
files=d.get('files')
if not isinstance(files,list) or not files: sys.exit(3)
print('\n'.join(files)); print('VERSION='+str(d.get('version','?')), file=sys.stderr)
PY
) || { echo "❌ $MANIFEST нечитаем или не содержит списка files — проверка НЕ выполнена" >&2; exit 2; }

VERSION=$(python3 -c "import json;print(json.load(open('$MANIFEST')).get('version','?'))" 2>/dev/null || echo '?')
echo "== Локальные артефакты против пакета $VERSION =="
echo

is_vendor() { printf '%s\n' "$VENDOR" | grep -qxF "$1"; }

# Все кандидаты: правила, скрипты, хуки, шаблоны
CANDIDATES=$(find .claude/rules .claude/patterns .claude/templates .claude/snippets \
                  scripts projects/*/scripts \
                  -type f \( -name '*.md' -o -name '*.sh' -o -name '*.cjs' -o -name '*.yml' \) \
             2>/dev/null | sed 's|^\./||' | sort -u)

MARKED=0; UNMARKED=0
UNMARKED_LIST=''

echo "-- Помечены: отслеживают заявку в кузницу --"
echo
while IFS= read -r f; do
  [ -z "$f" ] && continue
  case "$f" in *"$SELF") continue;; esac      # сам скрипт содержит искомую строку
  is_vendor "$f" && continue                   # вендорное не наше, его перезапишут
  if grep -q 'ЗАМЕЩЕНИЕ: отслеживает' "$f" 2>/dev/null; then
    MARKED=$((MARKED+1))
    PR=$(grep -m1 'ЗАМЕЩЕНИЕ: отслеживает' "$f" | sed 's/.*отслеживает //')
    ST=$(grep -m1 'Статус апстрима:' "$f" | sed 's/.*Статус апстрима: //')
    printf '  📌 %s\n     заявка: %s\n     статус: %s\n\n' "$f" "$PR" "$ST"
  else
    UNMARKED=$((UNMARKED+1))
    UNMARKED_LIST="${UNMARKED_LIST}${f}"$'\n'
  fi
done <<< "$CANDIDATES"

[ "$MARKED" -eq 0 ] && { echo "  ⚠ ни одного помеченного — метки потерялись при обновлении?"; FAIL=1; }

if [ "$UNMARKED" -gt 0 ]; then
  FAIL=1
  echo "-- ❌ НЕ ОТСЛЕЖИВАЮТСЯ: локальные, но без метки ($UNMARKED) --"
  echo
  echo "  Про эти файлы страж НИЧЕГО не знает. Если апстрим выпустит своё"
  echo "  правило на ту же тему, вы об этом не узнаете — и два места с одним"
  echo "  правилом начнут расходиться молча."
  echo
  printf '%s' "$UNMARKED_LIST" | sed 's/^/     · /'
  echo
  echo "  Что сделать с каждым: добавить шапку"
  echo "     > ЗАМЕЩЕНИЕ: отслеживает PR-NNN   (или: локальная политика, заявки нет)"
  echo "     > Статус апстрима: <...>"
  echo "  Файл, который апстрим не заберёт никогда, помечается ПОСТОЯННЫМ — но"
  echo "  помечается, а не молчит."
  echo
fi

echo "-- Вендорные правила пакета $VERSION — сверить глазами --"
echo
printf '%s\n' "$VENDOR" | grep '^\.claude/rules/' | sed 's|.claude/rules/|     |' | sort | tr '\n' ' ' | fold -s -w 92 | sed 's/^/ /'
echo; echo
echo "== Что проверить руками =="
echo "  1. Есть ли среди вендорных правил выше то, что покрывает наш локальный файл?"
echo "  2. Если есть — локальный УРЕЗАТЬ до того, чего в пакете нет, и поставить"
echo "     ссылку. Не оставлять оба целиком."
echo "  3. Если апстрим отказался включать — отметить ПОСТОЯННЫМ в его же метке."
echo
echo "  Вендорные файлы НЕ ПРАВИТЬ: обновление их перезапишет. Локальная политика"
echo "  живёт отдельными файлами — так port-conflicts-local.md пережил 1.9.0."

exit $FAIL
