#!/usr/bin/env bash
set -euo pipefail
: "${N8_APP_PASSWORD:?}" "${N8_MIGRATOR_PASSWORD:?}"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=app_password="$N8_APP_PASSWORD" --set=migrator_password="$N8_MIGRATOR_PASSWORD" <<'SQL'
CREATE ROLE n8_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'migrator_password';
CREATE ROLE n8_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
GRANT CREATE ON DATABASE n8 TO n8_migrator;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE,CREATE ON SCHEMA public TO n8_migrator;
GRANT USAGE ON SCHEMA public TO n8_app;
ALTER DEFAULT PRIVILEGES FOR ROLE n8_migrator IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO n8_app;
ALTER DEFAULT PRIVILEGES FOR ROLE n8_migrator IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO n8_app;
SQL
