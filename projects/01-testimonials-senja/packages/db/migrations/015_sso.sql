-- FR-016: вход через Yandex ID.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- КЛЮЧ УЧЁТНОЙ ЗАПИСИ — external_id, А НЕ EMAIL. Это несущее решение фичи, и оно
-- закреплено здесь схемой, а не дисциплиной вызывающего кода.
--
-- login.yandex.ru/info НЕ отдаёт признака подтверждённости адреса: поля email_verified в
-- ответе нет вовсе, и приложение программно не может отличить подтверждённый адрес от
-- вписанного в профиль руками. Auth.js называет связывание по совпадению адреса
-- allowDangerousEmailAccountLinking — опасность вынесена в имя настройки.
--
-- Захват при связывании по email работает В ОБЕ СТОРОНЫ:
--   1. атакующий ставит адрес жертвы в свой яндексовый профиль и входит к ней;
--   2. атакующий заранее регистрирует у нас учётку на адрес жертвы со своим паролем, и
--      жертва, войдя через Яндекс, попадает В ЧУЖУЮ учётку.
-- Второе направление НЕ лечится подтверждением адреса на нашей стороне — только отказом
-- от автосвязывания. Поэтому email в этой таблице не хранится и ключом не является.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists sso_identities (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references accounts(id) on delete cascade,
  -- CHECK, а не свободный текст: второй провайдер появится вместе с осознанной правкой
  -- схемы, а не опечаткой в коде. Опечатка создала бы отдельное пространство
  -- идентификаторов, и человек молча получил бы вторую учётку.
  provider text not null check (provider in ('yandex')),
  external_id text not null,
  created_at timestamptz not null default now(),
  -- УНИКАЛЬНОСТЬ НЕСЁТ НАГРУЗКУ, А НЕ УСКОРЕНИЕ. Два одновременных коллбэка с одним кодом —
  -- не выдумка: браузер повторяет запрос при разрыве, человек жмёт «назад». Связка
  -- «SELECT → если нет, INSERT» под READ COMMITTED здесь НЕ работает: оба видят «нет» и
  -- создают ДВЕ учётки на один яндексовый аккаунт, после чего человек попадает то в одну,
  -- то в другую. Ограничение БД закрывает это по построению — та же форма, что
  -- password_reset_tokens_account_active_idx и unique(payment_event_id) у начислений.
  unique (provider, external_id)
);

-- Обратный путь: «какие провайдеры привязаны к этой учётке» — для страницы настроек и для
-- проверки «у учётки есть хоть один способ входа» перед отвязкой.
create index if not exists sso_identities_account_idx on sso_identities (account_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- password_hash СТАНОВИТСЯ NULLABLE — учётка, созданная через Яндекс, пароля не имеет.
--
-- Это НЕ открывает дыру, и вот разбор по местам, а не заверение:
--   login.ts:127   `account?.password_hash ?? await dummyHash()` — NULL коалесцируется в
--                  заглушечный хеш от случайных байт, verifyPassword честно не сходится,
--                  счётчики пишутся, время неотличимо от «аккаунта нет». Свойство УЖЕ есть,
--                  не было только теста (AC-016.6 его добавляет).
--   register.ts    парольная регистрация всегда передаёт хеш — не меняется.
--   password-reset сброс задаёт хеш — не меняется.
--   password-change единственное место, которое ломается: verifyPassword(NULL) бросит, и
--                  маршрут отдаст 500 вместо отказа. Чинится тремя строками (AC-016.7).
--
-- Альтернатива «оставить NOT NULL и писать заглушечный хеш» отвергнута: это данные-ложь.
-- Она делает неразличимыми «пароля нет» и «пароль есть, но неизвестен», и молча ломает
-- сравнение-и-замену в смене пароля, которая сверяет хеш с хешем.
alter table accounts alter column password_hash drop not null;

-- Весь путь SSO идёт под app_service: человек не аутентифицирован в момент коллбэка,
-- контекста арендатора ещё нет — ровно как на пути восстановления пароля.
grant select, insert on sso_identities to app_service;

-- app_authenticated НАМЕРЕННО НЕ ПОЛУЧАЕТ НИЧЕГО. Соблазн выдать ей select «чтобы страница
-- настроек показала привязку» здесь — дыра: RLS на таблице не включён, а роль app_authenticated
-- работает ПОД RLS, и без политики она увидела бы привязки ВСЕХ учёток, а не своей.
-- Правильных выходов два: включить RLS с политикой по account_id, либо читать под app_service
-- уже установленным account_id. Отвязка и страница настроек вне объёма FR-016, поэтому
-- выбран fail-closed: прав нет вовсе. Выдать их позже — осознанная правка со своей политикой.
