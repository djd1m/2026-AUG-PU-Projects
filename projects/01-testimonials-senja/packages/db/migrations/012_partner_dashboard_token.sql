-- FR-011: партнёрский кабинет.
--
-- Зачем ОТДЕЛЬНЫЙ секрет, а не сам партнёрский код. Код публичен по назначению — это и
-- промокод, который вводит приглашённый при регистрации (referral.ts), и метка в
-- реферальной ссылке, которую партнёр распространяет по своей аудитории. Сделать его
-- ключом к странице с суммами начислений означало бы опубликовать эти суммы вместе со
-- ссылкой.
--
-- Хранится ХЕШ, а не токен: та же дисциплина, что у sessions.token_hash, и по той же
-- причине — компрометация БД не должна давать доступ к кабинетам.

alter table partner_codes
  add column if not exists dashboard_token_hash text;

-- Уникальность несёт двойную нагрузку: ускоряет сверку по хешу и делает совпадение двух
-- токенов ошибкой БД, а не тихим совпадением. NULL в уникальном индексе Postgres сам с
-- собой не конфликтует, поэтому коды без токена сосуществуют штатно.
create unique index if not exists partner_codes_dashboard_token_hash_idx
  on partner_codes (dashboard_token_hash);

