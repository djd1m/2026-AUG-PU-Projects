-- 018_paid_until.sql — у платного тарифа появляется СРОК, а у оплаты — свой ключ идемпотентности.
--
-- ЗАЧЕМ. Владелец зафиксировал цену «990 ₽ / 30 дней» (DEC-001, 2026-09-02). До этой миграции
-- applyTariffUpgrade делал `update projects set tier = 'paid'` и всё: в схеме не было НИ ОДНОЙ
-- колонки срока. Продавать месяц при такой записи значит обещать месяц, а выдавать пожизненно —
-- система физически не умела закончить оплаченный период.
--
-- Второе: ключ идемпотентности при создании платежа собирался как `${projectId}:${amount}`.
-- Ключ обязателен по контракту ЮKassa и работает ровно как задумано — повтор с тем же ключом
-- возвращает ТОТ ЖЕ платёж. Но у продления те же проект и та же сумма, поэтому второй месяц
-- вернул бы первый, уже оплаченный платёж: владелец нажал «продлить», попал на завершённую
-- оплату и решил, что всё прошло. Денег нет, срок не продлён, в журнале ничего. Ключ обязан
-- быть свой у каждой попытки — колонка ниже хранит его и делает повтор различимым в разборе.
--
-- ПОЧЕМУ NULL, А НЕ ДАТА В ПРОШЛОМ. `paid_until is null` означает «никогда не оплачивался» и
-- читается правилом badge как «badge требуется» — то же fail-closed, что у неизвестного тарифа.
-- Дата в прошлом означала бы «оплата была и кончилась»; это другое состояние, и подменять одно
-- другим при заведении проекта значило бы врать журналу.
--
-- Обратная совместимость не нужна и это ПРОВЕРЕНО, а не предположено: на стенде ноль проектов
-- с tier='paid' и ноль строк checkout_sessions (запрос выполнен 2026-09-02 перед миграцией).

ALTER TABLE projects ADD COLUMN IF NOT EXISTS paid_until timestamptz NULL;

COMMENT ON COLUMN projects.paid_until IS
  'До какого момента действует платный тариф. NULL — никогда не оплачивался. '
  'Badge не требуется, только если tier = paid И paid_until в будущем.';

ALTER TABLE checkout_sessions ADD COLUMN IF NOT EXISTS idempotence_key uuid NULL;

COMMENT ON COLUMN checkout_sessions.idempotence_key IS
  'Ключ, отправленный провайдеру при создании платежа. Свой у КАЖДОЙ попытки оплаты: общий '
  'ключ вернул бы прежний платёж вместо нового и сделал продление невозможным.';
