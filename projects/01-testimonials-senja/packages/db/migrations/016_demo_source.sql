-- Третий источник отзыва: 'demo'.
--
-- Заведён по прямому предписанию комментария в 013_import.sql: «третий источник появится
-- только вместе с осознанной правкой схемы, а не опечаткой в коде». Это она.
--
-- ЗАЧЕМ ОТДЕЛЬНОЕ ЗНАЧЕНИЕ, а не 'form' для демо-данных. Записать демонстрационный отзыв
-- как пришедший из формы — положить в колонку ложь. Ровно тот класс, по которому в FR-016
-- отвергли заглушечный хеш вместо NULL: данные-ложь делают неразличимыми два разных
-- состояния, и различить их потом нечем.
--
-- А различать придётся. Отзыв, сочинённый для демонстрации, и отзыв, оставленный живым
-- человеком, — юридически разные вещи: FTC Rule 16 CFR Part 465 (до $53 088 за нарушение)
-- карает выдачу сочинённого за настоящее. Пометка в САМИХ ДАННЫХ означает, что демо всегда
-- можно найти и убрать одним запросом, а рендер может показать отметку, не гадая.
--
-- Не путать с transcript_source='machine': то помечает МАШИННУЮ РАСШИФРОВКУ речи живого
-- человека — текст принадлежит автору. Здесь помечается текст, автора не имеющий вовсе.

alter table testimonials drop constraint if exists testimonials_source_check;
alter table testimonials add constraint testimonials_source_check
  check (source in ('form', 'import', 'demo'));
