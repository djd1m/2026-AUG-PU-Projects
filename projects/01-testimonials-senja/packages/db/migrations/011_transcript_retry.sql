-- packages/db/migrations/011_transcript_retry.sql
--
-- FR-012: повтор транскрипции при сбое STT.
--
-- Зачем в СХЕМЕ, а не в памяти процесса: воркер перезапускается (`restart: unless-stopped`),
-- и счётчик в процессе означал бы, что каждый перезапуск обнуляет историю попыток —
-- то есть при регулярных рестартах повторы стали бы бесконечными.
--
-- `transcript_status` НЕ трогаем. Соблазн добавить 'retrying' есть, но четвёртое состояние
-- пришлось бы учесть в каждом месте, читающем статус, включая витрину и модерацию.
-- Ожидание повтора выражается парой «pending + срок в будущем», и этого достаточно.

alter table testimonials
  -- Сколько попыток уже сделано. Не обнуляется при успехе: «расшифровалось с третьей
  -- попытки» — факт, полезный при разборе (NFR-012.5).
  add column if not exists transcript_attempts int not null default 0,
  -- Момент, раньше которого строку брать нельзя. NULL = можно брать сейчас.
  -- Пишется clock_timestamp() + задержка, а НЕ now(): now() в Postgres это время
  -- НАЧАЛА транзакции, а транзакция открывается до сетевого вызова к STT, который
  -- может длиться минуты. Срок от now() оказался бы в прошлом уже на COMMIT.
  add column if not exists transcript_next_attempt_at timestamptz;

