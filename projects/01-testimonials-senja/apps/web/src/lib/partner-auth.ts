// FR-011 — аутентификация партнёра для кабинета.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗДЕСЬ ОТДЕЛЬНЫЙ СЕКРЕТ, А НЕ САМ ПАРТНЁРСКИЙ КОД.
// Код публичен ПО НАЗНАЧЕНИЮ, и это два работающих пути, а не предположение: он же
// промокод, который вводит приглашённый при регистрации (referral.ts:33-38), и он же
// метка в реферальной ссылке, кладущаяся в cookie (referral.ts:42-44). Партнёр
// распространяет код по своей аудитории — в этом весь смысл. Сделать его ключом к
// странице с суммами начислений значило бы опубликовать эти суммы вместе со ссылкой.
//
// ПОЧЕМУ СЕКРЕТ В COOKIE, А НЕ В АДРЕСЕ. Адрес утекает тремя путями, и ни один не
// касается тела POST: Referer любому внешнему ресурсу на странице; история браузера с
// облачной синхронизацией; журналы прокси, которые переживают всё остальное.
//
// ПОЧЕМУ ЛОКА НЕТ ВООБЩЕ. Четыре редакции документов спорили о ключе лока, пока не был
// задан правильный вопрос: что этот счётчик защищает? Пространство токена — 2^256,
// перебором его не берут ни с локом, ни без. Счётчик защищает от НАГРУЗКИ, а для этого
// атомарность не нужна. Измеренная цена атомарности оказалась выше защищаемого: ждущий
// лок ронял пропускную способность с ~7800 до ~1180 попыток/с, очередь копилась в ОБЩЕМ
// пуле, и при 6000 попыток витрина, виджет и дашборд получали p95 = 5 с и прямой отказ.
// Принятая цена приблизительного счётчика названа числом: при залпе N=40 с одного адреса
// проходит ~37 попыток вместо 30.
//
// ЗАПИСЫВАЕТСЯ ТОЛЬКО НЕУДАЧА — как NFR-009.4 входа: «запись при успехе заперла бы
// активного владельца им самим». Партнёр, открывший кабинет тридцать раз за час, иначе
// запирал бы себя сам, а за одним NAT это делали бы несколько партнёров совместно.
// ─────────────────────────────────────────────────────────────────────────────

import { createHash, randomBytes } from 'node:crypto';
import type { PoolClient } from 'pg';
import { rateLimit } from '@proofwall/db';
import { hashKey } from './login';

export const PARTNER_COOKIE = 'pw_partner';
/** Столько же, сколько у сессии владельца. 2^256 — перебор нереалистичен. */
export const PARTNER_TOKEN_BYTES = 32;
export const PARTNER_IP_SCOPE = 'partner_token_ip';
/** 30, а не 5: за одним NAT сидят живые люди, и цена ложного отказа здесь выше цены
 *  перевыполнения порога — угадать токен всё равно нельзя. */
export const PARTNER_IP_THRESHOLD = 30;
export const PARTNER_WINDOW = { seconds: 3600 } as const;
/** Успешные показы тоже стоят соединения общего пула и шести запросов, и до этой правки не
 *  ограничивались НИЧЕМ: 200 последовательных сверок проходили все, 100 одновременных
 *  показов одним токеном поднимали p95 соседнего пути с 15 до 151 мс.
 *
 *  Ключ — по ЛИЧНОСТИ ПАРТНЁРА, а не по адресу: за одним NAT сидят разные партнёры, и общий
 *  ключ запирал бы соседа. Ровно то решение, которым FR-010 снял такое же возражение
 *  (PWCHANGE_SUCCESS_SCOPE, ключ по accountId). Обоснование «записываем только неудачу, как
 *  NFR-009.4 входа» было верным, но неполным: предыдущая фича этот аргумент уже опровергла —
 *  успешный путь тоже стоит ресурса.
 *
 *  200/час — с большим запасом над живым сценарием (партнёр смотрит когорту несколько раз в
 *  день) и на порядок ниже вредного. Исчерпание не отбирает доступ навсегда: через час окно
 *  сдвигается. */
export const PARTNER_SUCCESS_SCOPE = 'partner_dashboard_success';
export const PARTNER_SUCCESS_THRESHOLD = 200;

/** Свой хеш, а НЕ hashSessionToken: та подмешивает SESSION_SECRET, и переиспользование
 *  связало бы два пространства секретов — ротация SESSION_SECRET обнулила бы все
 *  партнёрские токены заодно с сессиями, и причина была бы неочевидна. Соли здесь не
 *  нужно: 32 случайных байта не берутся радужной таблицей. */
export function hashPartnerToken(token: string): string {
  return createHash('sha256').update(token).digest('hex');
}

export function generateDashboardToken(): string {
  return randomBytes(PARTNER_TOKEN_BYTES).toString('base64url');
}

export type PartnerAuth =
  // `code` здесь НЕТ намеренно: это публичное значение, и дальше по стеку оно не едет.
  | { ok: true; partnerCodeId: string }
  // Причины отказа НЕТ — это реализация NFR-011.3 формой типа: вызывающий физически не
  // может отдать разные ответы на «токена нет», «код отозван» и «мусор», потому что
  // различить их нечем. «Такой партнёр есть, но код отозван» — уже утечка.
  | { ok: false; tooMany: boolean };

/**
 * ОДНА транзакция, и она общая для обеих дверей — приёма токена и показа кабинета.
 *
 * Вложенного `withService` быть не должно: он нереентрантен (`tenant.ts:30` — безусловный
 * `pool.connect()`), и обёртка поверх функции, которая сама открывает транзакцию, даёт
 * самоблокировку на пуле. Измерено на схеме, где обёртка была: при 31 одновременном
 * запросе POOL_TIMEOUT у 19 из 31, p95 продуктового пробника 5005 мс, прямой отказ витрины.
 * Порог совпадал с размером пула — внешние обёртки занимали все 30 соединений, а
 * внутренние транзакции ждали их же.
 */
export async function resolvePartner(
  client: PoolClient,
  token: string,
  ip: string,
): Promise<PartnerAuth> {
  const keyIp = hashKey(PARTNER_IP_SCOPE, ip);

  // Дешёвый сброс: превышение отвечает сразу и отпускает соединение.
  if (await rateLimit.exceeded(PARTNER_IP_SCOPE, keyIp, PARTNER_WINDOW, PARTNER_IP_THRESHOLD, client)) {
    return { ok: false, tooMany: true };
  }

  // Хеш считается ЗДЕСЬ, в коде. Сырой токен в SQL не уезжает вовсе: он попал бы в
  // pg_stat_statements, в log_statement при отладке и в текст ошибки при сбое — то есть
  // ровно в журнал, названный третьей из трёх утечек.
  const tokenHash = hashPartnerToken(token);

  // status = 'active' в ЭТОМ же условии, а не отдельной проверкой с другим ответом.
  // И проверяется он на КАЖДОМ обращении, поэтому отзыв кода и ротация токена действуют
  // немедленно, а не до истечения cookie.
  const { rows } = await client.query<{ id: string }>(
    "select id from partner_codes where dashboard_token_hash = $1 and status = 'active'",
    [tokenHash],
  );

  const partner = rows[0];
  if (!partner) {
    await rateLimit.record(PARTNER_IP_SCOPE, keyIp, client);
    return { ok: false, tooMany: false };
  }

  // Путь УСПЕХА тоже ограничен — ключом по личности партнёра, не по адресу.
  const keyPartner = hashKey(PARTNER_SUCCESS_SCOPE, partner.id);
  if (await rateLimit.exceeded(
    PARTNER_SUCCESS_SCOPE, keyPartner, PARTNER_WINDOW, PARTNER_SUCCESS_THRESHOLD, client)) {
    return { ok: false, tooMany: true };
  }
  await rateLimit.record(PARTNER_SUCCESS_SCOPE, keyPartner, client);

  return { ok: true, partnerCodeId: partner.id };
}
