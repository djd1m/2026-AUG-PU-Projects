// Куда возвращать браузер после входа (FR-009.5).
//
// Вынесено из клиентского компонента ОТДЕЛЬНЫМ модулем ровно затем, чтобы это можно было
// проверить тестом: пока функция жила внутри login-form.tsx, ни один тест её не касался,
// и подмена на `value.startsWith('/')` проходила зелёной (ревью B-1).
//
// «Начинается со слеша» — дырявая проверка: `//evil.example/x` тоже начинается со слеша и
// является ПРОТОКОЛ-ОТНОСИТЕЛЬНЫМ адресом, то есть открытым редиректом на чужой домен.
// Этот же дефект уже ловился в виджете, поэтому здесь сразу точная форма пути.

/** Ровно один ведущий слеш, дальше — только безопасные символы пути. */
const RELATIVE_PATH = /^\/(?!\/)[A-Za-z0-9/_-]*$/;

/** null, если значение непригодно: вызывающий обязан подставить свой запасной адрес. */
export function safeNextPath(value: unknown): string | null {
  if (typeof value !== 'string' || value === '') return null;
  return RELATIVE_PATH.test(value) ? value : null;
}
