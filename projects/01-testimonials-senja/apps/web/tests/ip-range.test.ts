// Сопоставление IP с сетью — несущая часть аутентификации вебхука ЮKassa (D-009).
// Провайдер не подписывает уведомления, поэтому ошибка здесь = приём подделки.

import { describe, expect, it } from 'vitest';
import { ipInAnyCidr, ipInCidr } from '../src/lib/ip-range';

describe('IPv4 — границы сети считаются, а не угадываются', () => {
  it('/27 покрывает ровно 32 адреса: .0-.31', () => {
    expect(ipInCidr('185.71.76.0', '185.71.76.0/27')).toBe(true);
    expect(ipInCidr('185.71.76.31', '185.71.76.0/27')).toBe(true);
    expect(ipInCidr('185.71.76.32', '185.71.76.0/27')).toBe(false);
  });

  it('ЛОВУШКА строкового префикса: .100 совпадает по тексту, но НЕ входит в /27', () => {
    // "185.71.76." — общий префикс у обоих, но 100 > 31.
    expect(ipInCidr('185.71.76.100', '185.71.76.0/27')).toBe(false);
    expect(ipInCidr('185.71.76.255', '185.71.76.0/27')).toBe(false);
  });

  it('/25 покрывает .0-.127, но не .128', () => {
    expect(ipInCidr('77.75.153.0', '77.75.153.0/25')).toBe(true);
    expect(ipInCidr('77.75.153.127', '77.75.153.0/25')).toBe(true);
    expect(ipInCidr('77.75.153.128', '77.75.153.0/25')).toBe(false);
  });

  it('вторая половина /25 — отдельная сеть', () => {
    expect(ipInCidr('77.75.154.128', '77.75.154.128/25')).toBe(true);
    expect(ipInCidr('77.75.154.255', '77.75.154.128/25')).toBe(true);
    expect(ipInCidr('77.75.154.127', '77.75.154.128/25')).toBe(false);
  });

  it('одиночный адрес без маски — точное совпадение', () => {
    expect(ipInCidr('77.75.156.11', '77.75.156.11')).toBe(true);
    expect(ipInCidr('77.75.156.12', '77.75.156.11')).toBe(false);
  });

  it('соседние /8-сети не смешиваются (проверка знакового сдвига)', () => {
    expect(ipInCidr('10.0.0.1', '10.0.0.0/8')).toBe(true);
    expect(ipInCidr('11.0.0.1', '10.0.0.0/8')).toBe(false);
    expect(ipInCidr('128.0.0.1', '128.0.0.0/8')).toBe(true);
    expect(ipInCidr('129.0.0.1', '128.0.0.0/8')).toBe(false);
  });

  it('/32 — ровно один адрес, /0 — любой', () => {
    expect(ipInCidr('1.2.3.4', '1.2.3.4/32')).toBe(true);
    expect(ipInCidr('1.2.3.5', '1.2.3.4/32')).toBe(false);
    expect(ipInCidr('203.0.113.9', '0.0.0.0/0')).toBe(true);
  });

  it('мусор и подделки формата отклоняются', () => {
    for (const bad of [
      '', ' ', 'не адрес', '1.2.3', '1.2.3.4.5', '256.1.1.1', '1.2.3.-1',
      '1.2.3.4abc', '0x7f.0.0.1', '1.2.3.04',
    ]) {
      expect(ipInCidr(bad, '0.0.0.0/0'), bad).toBe(false);
    }
  });

  it('ведущие нули не принимаются: "010" читается по-разному разными парсерами', () => {
    expect(ipInCidr('185.071.76.1', '185.71.76.0/27')).toBe(false);
  });

  it('битая маска отклоняется, а не трактуется вольно', () => {
    for (const bad of ['185.71.76.0/33', '185.71.76.0/-1', '185.71.76.0/abc', '185.71.76.0/']) {
      expect(ipInCidr('185.71.76.1', bad), bad).toBe(false);
    }
  });
});

describe('IPv6', () => {
  it('/32 ЮKassa покрывает свои адреса', () => {
    expect(ipInCidr('2a02:5180::1', '2a02:5180::/32')).toBe(true);
    expect(ipInCidr('2a02:5180:ffff:ffff:ffff:ffff:ffff:ffff', '2a02:5180::/32')).toBe(true);
    expect(ipInCidr('2a02:5181::1', '2a02:5180::/32')).toBe(false);
    expect(ipInCidr('2a03:5180::1', '2a02:5180::/32')).toBe(false);
  });

  it('семейства не смешиваются', () => {
    expect(ipInCidr('2a02:5180::1', '185.71.76.0/27')).toBe(false);
    expect(ipInCidr('185.71.76.1', '2a02:5180::/32')).toBe(false);
  });

  it('IPv4-mapped адрес сравнивается как IPv4', () => {
    // Node отдаёт такой вид, когда IPv4-клиент приходит на IPv6-сокет.
    expect(ipInCidr('::ffff:185.71.76.1', '185.71.76.0/27')).toBe(true);
    expect(ipInCidr('::ffff:185.71.76.100', '185.71.76.0/27')).toBe(false);
  });

  it('адрес в скобках и с зоной разбирается', () => {
    expect(ipInCidr('[2a02:5180::1]', '2a02:5180::/32')).toBe(true);
    expect(ipInCidr('fe80::1%eth0', 'fe80::/16')).toBe(true);
  });

  it('двойное "::" неоднозначно и отклоняется', () => {
    expect(ipInCidr('2a02::5180::1', '2a02:5180::/32')).toBe(false);
  });

  it('мусор отклоняется', () => {
    for (const bad of ['2a02:5180:::1', 'gggg::1', '2a02:5180:1:2:3:4:5:6:7']) {
      expect(ipInCidr(bad, '::/0'), bad).toBe(false);
    }
  });
});

describe('ipInAnyCidr — реальный список сетей ЮKassa', () => {
  // Список из https://yookassa.ru/developers/using-api/webhooks
  const NETS = [
    '185.71.76.0/27', '185.71.77.0/27', '77.75.153.0/25',
    '77.75.156.11', '77.75.156.35', '77.75.154.128/25', '2a02:5180::/32',
  ] as const;

  it.each(['185.71.76.5', '185.71.77.30', '77.75.153.99', '77.75.156.11', '77.75.156.35',
           '77.75.154.200', '2a02:5180:abcd::1', '::ffff:185.71.76.5'])(
    'адрес ЮKassa %s принимается', (ip) => {
      expect(ipInAnyCidr(ip, NETS)).toBe(true);
    },
  );

  it.each(['185.71.76.32', '185.71.78.1', '77.75.153.128', '77.75.156.12', '77.75.154.127',
           '2a02:5181::1', '8.8.8.8', '127.0.0.1', '10.0.0.1', ''])(
    'чужой адрес %s отклоняется', (ip) => {
      expect(ipInAnyCidr(ip, NETS)).toBe(false);
    },
  );

  it('пустой список не пропускает никого', () => {
    expect(ipInAnyCidr('185.71.76.5', [])).toBe(false);
  });
});
