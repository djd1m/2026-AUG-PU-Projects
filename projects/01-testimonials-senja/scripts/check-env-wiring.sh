#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────
# ЗАМЕЩЕНИЕ: отслеживает PR-014
# Статус апстрима: апстрим выпустил check-ports.cjs (экспозиция), но НЕ проброс переменных. Пока не пересекается
#
# Зачем метка. Локальный артефакт — это прототип и доказательство для заявки,
# а не вечная копия. Когда апстрим реализует заявку, этот файл обязан быть либо
# удалён, либо урезан до того, чего в пакете нет. Два места с одним правилом —
# худший исход, чем отсутствие правила: они расходятся молча.
# Проверять при каждом обновлении пакета: bash scripts/check-superseded.sh
# ─────────────────────────────────────────────────────────────────────
# Полнота проброса переменных окружения в сервисы compose.
#
# Ловит класс дефектов, при котором приложение стартует нормально и тесты зелёные, а
# наружу выдаётся неверное. Конкретный случай: BASE_URL читался кодом, но отсутствовал
# в environment у web — каждая выданная владельцу ссылка вела на http://localhost:3000.
# Не поймали ни старт контейнера (есть дефолт), ни юнит-тесты (сломана не функция, а то,
# что до неё не доехало значение), ни браузерная проверка (страницы открывались).
#
# Сверяются ДВА множества, и .env.example НЕ является опорой: на прогоне выяснилось, что
# он сам был неполон — BASE_URL отсутствовал и в нём. Опираться на неполный файл значит
# унаследовать его пробел.
#
# Запуск:  bash scripts/check-env-wiring.sh [compose-файлы...]
# Коды:    0 — всё проброшено, 1 — есть потери

set -uo pipefail
cd "$(dirname "$0")/.."
FAIL=0

# Переменные, которые читаются кодом, но приходят не из compose: их задаёт рантайм,
# сборка или тестовое окружение. Список ЯВНЫЙ — молчаливых исключений быть не должно.
# NEXT_PHASE ставит сам Next на время сборки (phase-production-build); в рантайме её
# нет и быть не должно — по ней urls.ts отличает сборку от прода, где BASE_URL обязателен.
# PGPOOL_MAX и PGPOOL_CONNECTION_TIMEOUT_MS убраны из исключений (D-010): теперь
# они приходят из compose, и страж обязан проверять их проброс, а не пропускать.
ALLOWED='NODE_ENV|NEXT_PHASE|TEST_DATABASE_URL|S3_REGION|YOOKASSA_API_URL|PAYMENT_PROVIDER|NEXT_PUBLIC_[A-Z0-9_]*'

COMPOSE_ARGS=()
if [ "$#" -gt 0 ]; then for f in "$@"; do COMPOSE_ARGS+=(-f "$f"); done
else COMPOSE_ARGS=(-f docker-compose.yml); fi

echo "== Переменные, читаемые кодом, доезжают до сервиса =="

# Общие пакеты монорепо сканируются ВМЕСТЕ с сервисом, который их импортирует.
# Ревью L-5: PGPOOL_MAX и PGPOOL_CONNECTION_TIMEOUT_MS читаются в packages/db/src, а
# цикл ходил только по apps/ и services/ — страж утверждал, что проверяет их проброс,
# и не проверял.
shared_for() {  # $1 — каталог сервиса; печатает каталоги общих пакетов, которые он тянет
  for pkg in packages/*/; do
    [ -d "$pkg/src" ] || continue
    name=$(python3 -c "import json,sys;print(json.load(open('$pkg/package.json'))['name'])" 2>/dev/null) || continue
    # Комментарии ИСКЛЮЧЕНЫ и здесь. services/worker/src/db.ts упоминает @proofwall/db
    # в комментарии («работаем напрямую по SQL, а не через @proofwall/db») — и страж
    # решал, что воркер этот пакет использует. Ложная связь тянула в его список чужие
    # переменные. Тот же класс, что чтение комментариев ниже; исправлено вместе.
    grep -rhv -E '^\s*(//|\*|/\*)' "$1/src" 2>/dev/null | grep -qF "$name" \
      && printf '%s/src ' "$pkg"
  done
}

for svc_dir in apps/web services/worker services/transcribe; do
  [ -d "$svc_dir/src" ] || continue
  svc=$(basename "$svc_dir")
  [ "$svc" = "web" ] && svc=web

  # [A-Z0-9_]+ — с ЦИФРАМИ: без них S3_ENDPOINT обрезается до "S" и даёт ложное
  # срабатывание (поймано при написании этой проверки).
  # ДВЕ формы чтения, и вторая обязательна. Прямое `process.env.NAME` находится
  # регэкспом, но имя может уехать в СТРОКОВЫЙ аргумент помощника
  # (`positiveIntFromEnv('PGPOOL_MAX', 30)`) — тогда первая форма его не видит.
  # Кавычки ОБЕ: воркер пишет "PGPOOL_MAX", веб — 'PGPOOL_MAX'. Шаблон под одну из них
  # молча пропускал половину кода — тот же класс, что чтение комментариев ниже.
  # ЗАКРЫВАЮЩУЮ кавычку не захватываем: с ней имя переставало быть концом строки,
  # и следующий grep с якорем $ не находил ничего. Страж молчал при живом пробеле.
  # Помощники перечислены явно: молчаливое расширение шаблона однажды начнёт ловить
  # посторонние строки и утопит настоящие потери в шуме.
  #
  # НО У ЯВНОГО СПИСКА ЕСТЬ ЦЕНА, и она реализовалась: FR-015 ввёл `requireEnv`, его в списке
  # не было, и страж отвечал «все переменные проброшены», пока RESEND_API_KEY и MAIL_FROM не
  # были проброшены НИКУДА. Зелёный на ложном свойстве — то же, что отсутствие проверки,
  # только хуже: он ещё и заверяет.
  #
  # Отсюда правило сопровождения: НОВЫЙ ПОМОЩНИК ЧТЕНИЯ ОКРУЖЕНИЯ ДОБАВЛЯЕТСЯ СЮДА В ТОМ ЖЕ
  # КОММИТЕ, что и сам помощник. Проверить легко: временно убрать имя из списка и убедиться,
  # что страж покраснел.
  ENV_HELPERS='positiveIntFromEnv|requireEnv'
  # shellcheck disable=SC2086
  scan_dirs="$svc_dir/src $(shared_for "$svc_dir")"
  # Комментарии выкидываем ДО поиска: в них имена переменных упоминаются по делу
  # (`Number(process.env.X ?? 30)` в объяснении дефекта) и чтением не являются.
  # Без этого страж выдавал переменную «X» — ложное срабатывание, а страж, кричащий
  # впустую, отключают вместе с настоящими находками.
  # shellcheck disable=SC2086
  code=$(grep -rhv -E '^\s*(//|\*|/\*)' $scan_dirs 2>/dev/null)
  used=$( { printf '%s\n' "$code" | grep -oE 'process\.env\.[A-Z][A-Z0-9_]*' | sed 's/.*env\.//';
            printf '%s\n' "$code" \
              | grep -oE "(${ENV_HELPERS})\((\"|')[A-Z][A-Z0-9_]*" \
              | grep -oE '[A-Z][A-Z0-9_]*$'; } | sort -u)
  [ -z "$used" ] && continue

  passed=$(docker compose "${COMPOSE_ARGS[@]}" config 2>/dev/null \
           | sed -n "/^  ${svc}:/,/^  [a-z]/p" \
           | grep -oE '^[[:space:]]+[A-Z][A-Z0-9_]*:' | tr -d ' :' | sort -u)

  missing=$(comm -23 <(echo "$used") <(echo "$passed") | grep -vxE "$ALLOWED" || true)

  if [ -n "$missing" ]; then
    while read -r v; do
      [ -n "$v" ] && { printf '  ❌ %s: %s читается кодом, но не передаётся сервису\n' "$svc" "$v"; FAIL=1; }
    done <<<"$missing"
  else
    printf '  ✅ %s: все читаемые переменные проброшены\n' "$svc"
  fi
done

if [ "$FAIL" -ne 0 ]; then
  echo
  echo "     Добавить в environment соответствующего сервиса в docker-compose.yml."
  echo "     Приложение стартует и без них — ошибка видна только в поведении."
fi
exit $FAIL
