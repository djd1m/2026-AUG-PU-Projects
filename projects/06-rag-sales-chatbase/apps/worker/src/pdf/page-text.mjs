// Текст страницы PDF из элементов pdfjs getTextContent (ExtractPdf п.2). Чистый модуль: вынесен из extract-child.mjs,
// который исполняется при импорте, чтобы склейку можно было проверить тестом. Сборка воркера копирует его в dist/pdf
// рядом с extract-child.mjs (apps/worker/package.json; страж — tests/extract-text-separators.test.ts).
//
// Склейка — ПРЕЖНЯЯ, байт в байт (extract-text-separators, A-N6-060): разделители между фрагментами строки и переводы
// строк расставляет сам pdfjs (getTextContent вставляет пробел-элемент по зазору и hasEOL по смене строки, с учётом
// поворота, индексов и направления письма). Проверено настоящим документом: два фрагмента одной строки через зазор
// дают «Стрижка 1500» и на прежнем коде. Своя геометрия поверх этого дублировала pdfjs грубее и вносила порчи
// (повёрнутый текст, надстрочные индексы — ревью Codex, находки 2–4), поэтому не применяется.

// Текст страницы: элементы pdfjs + переводы строк; пробельные серии схлопываются. Регэкспы — одиночные
// классы символов с квантификатором, без вложенности: линейны.
export function pageText(items) {
  let text = '';
  for (const item of items) {
    if (typeof item.str === 'string') text += item.str;
    if (item.hasEOL) text += '\n';
  }
  return text.replace(/[ \t \f\v]+/g, ' ').replace(/ ?\n ?/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
}
