-- Расширение закрытого набора `recognition.failure_reason` до ДЕСЯТИ значений (DEC-A-018).
--
-- Почему отдельным файлом, а не правкой 001: 001 уже применён, и раннер по построению
-- отказывается переприменять изменённый файл — расхождение схемы и журнала должно быть
-- ошибкой, а не тихой правкой задним числом. Номер файла задаёт порядок однозначно.
--
-- `timeout` нужен ЗДЕСЬ И СЕЙЧАС: уборщик застрявших заданий (`sweepStuckScans`, DEC-A-015)
-- переводит в него задание, которое не взял ни один воркер за 5 минут, и задание с
-- исчерпанными тремя захватами. Без этого значения предел `lease_fence < 3` выразить
-- нечем: задание стало бы незахватываемым и провисело бы в `queued` вечно.
--
-- `normalize` добавляется ВМЕСТЕ с ним, хотя пишет его фича `scan-pipeline`. Причина не в
-- удобстве: `Architecture.md` и `Pseudocode.md` — владельцы физической и логической модели —
-- уже объявляют набор из ДЕСЯТИ значений. Схема, отстающая от документа, который ею
-- управляет, и есть то самое «два места с одним правилом», которые расходятся молча.

ALTER TYPE recognition_failure_reason ADD VALUE IF NOT EXISTS 'timeout';
ALTER TYPE recognition_failure_reason ADD VALUE IF NOT EXISTS 'normalize';
