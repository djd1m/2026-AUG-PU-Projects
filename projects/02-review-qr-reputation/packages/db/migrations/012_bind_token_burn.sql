-- 012_bind_token_burn.sql — одноразовость токена привязки переносится с bound_at на сам хеш.
--
-- ЧТО СЛОМАЛОСЬ У ВЛАДЕЛЬЦА. Кнопка «уведомления» в кабинете обнуляла chat_id и bound_at в
-- момент НАЖАТИЯ. Владелец открыл страницу посмотреть ссылку — и доставка умерла молча:
-- уведомления пошли в статус failed/channel_not_bound, а узнал он об этом только когда гость
-- оставил отзыв и в Telegram ничего не пришло. Кнопка уничтожала рабочее состояние без
-- предупреждения и без отмены.
--
-- ПОЧЕМУ ОДНОЙ ПРАВКИ В КАБИНЕТЕ МАЛО. Убрать обнуление недостаточно: нотифаер завершал
-- привязку условием `bound_at is null`, то есть после первой успешной привязки НИ ОДИН новый
-- токен уже не сработал бы никогда — перепривязка при смене телефона стала бы невозможной.
-- Две правки держатся только вместе, и это одна фича, а не две.
--
-- НОВЫЙ ИНВАРИАНТ. Одноразовость обеспечивает не флаг, а УНИЧТОЖЕНИЕ хеша: успешный /start
-- перезаписывает bind_token_hash случайными байтами, которым не соответствует ни один токен.
-- Отсюда три свойства сразу:
--   · токен срабатывает ровно один раз (после успеха его хеша в таблице больше нет);
--   · действующая привязка живёт до УСПЕХА нового /start, а не до намерения его получить;
--   · перепривязка возможна всегда — кабинет пишет свежий хеш, старый диплинк умирает.
--
-- Отсюда и грант: нотифаеру нужно ПИСАТЬ bind_token_hash, а не только читать. Права выдаются
-- по колонкам (как в 009), а не таблицей целиком.

GRANT UPDATE (bind_token_hash) ON channel_bindings TO app_notify;
