#!/bin/bash
# Периодическая чистка ТОЛЬКО нашего и заведомо восстановимого.
# На машине 96 контейнеров чужих проектов — `docker system prune` здесь ЗАПРЕЩЁН.
# Заслужено 22.09.2026: диск с 15 ГБ упал до 9 за день пересборок.
set -u
BEFORE=$(df --output=avail -BG / | tail -1 | tr -dc 0-9)
echo "свободно до: ${BEFORE}G"

# 1. НЕИСПОЛЬЗУЕМЫЙ кэш сборки. Фильтр по возрасту здесь бесполезен: наш кэш
#    создаётся в тот же день, что и чистится. Берём по признаку «не используется»
#    (ACTIVE=0 проверяется до запуска), а не по возрасту.
#    Это КЭШ: пересоздаётся. Общий на машину — первая сборка после чистки медленнее.
docker builder prune -f 2>/dev/null | tail -1

# 2. Наши тестовые тома. Каждый прогон и так накатывает миграции с нуля,
#    так что сохранять между прогонами нечего — а чистая база честнее.
#    ВНИМАНИЕ: только проект n5-clipmaker-test. Демо-стенд n5-clipmaker НЕ трогаем.
#    Тома заняты, пока поднят тестовый стек, — сначала опускаем ЕГО (только его).
docker compose --project-directory . --env-file "${N5_TEST_ENV:-/tmp/n5-test.env}" --profile test down -v --remove-orphans 2>/dev/null | tail -1
docker volume ls --format '{{.Name}}' | grep '^n5-clipmaker-test_' | xargs -r docker volume rm 2>/dev/null | wc -l | xargs echo "  удалено оставшихся наших тестовых томов:"

# 3. Образы, оставшиеся без тега после пересборки — они ничьи по определению.
docker image prune -f 2>/dev/null | tail -1

AFTER=$(df --output=avail -BG / | tail -1 | tr -dc 0-9)
echo "свободно после: ${AFTER}G (освобождено $((AFTER-BEFORE))G)"
