import { expect, it } from 'vitest';
import { pluralRu } from '../apps/web/src/lib/plural-ru';
it.each([
  [0, 'моментов'], [1, 'момент'], [2, 'момента'], [4, 'момента'], [5, 'моментов'],
  [11, 'моментов'], [12, 'моментов'], [14, 'моментов'], [21, 'момент'], [22, 'момента'],
  [25, 'моментов'], [101, 'момент'], [111, 'моментов'],
] as const)('%i → %s', (n, expected) => {
  expect(pluralRu(n, ['момент', 'момента', 'моментов'])).toBe(expected);
  expect(pluralRu(n, ['ваш', 'ваши', 'ваши'])).toBe(expected === 'момент' ? 'ваш' : 'ваши');
});
