#!/bin/bash
# Сторож хоста после операции ВНЕ run() из render.sh (probe вручную, stills, раскадровка, gate-*.sh) — модуль 06 §3.
#   T0=$(date '+%Y-%m-%d %H:%M:%S'); <операция с контейнером promo-<proj>-<шаг>>
#   bash .claude/skills/promo-video/scripts/gate-watchdog.sh promo-<proj>-<шаг> "$T0"
# Ищет в журнале сторожа строки ПОСЛЕ T0 с именем контейнера в кавычках (формат: [YYYY-MM-DD HH:MM:SS] … 'имя' …).
# Коды: 0 — сторож контейнер не трогал · 1 — трогал (строки выведены; замер/результат операции недействителен) ·
#       2 — проверка НЕ выполнена (журнал не читается, пуст, нет строк после T0 — сторож мог не работать, T0 не распознан).
set -uo pipefail
NAME=${1:-}; T0=${2:-}; LOG=${WATCHDOG_LOG:-/var/log/crypto-watchdog/watchdog.log}
[[ "$NAME" =~ ^promo-[a-z0-9-]+$ ]] || { echo "❌ имя контейнера «$NAME» не вида promo-<proj>-<шаг> — НЕ выполнено" >&2; exit 2; }
[[ "$T0" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}\ [0-9]{2}:[0-9]{2}:[0-9]{2}$ ]] || { echo "❌ T0 «$T0» не вида 'YYYY-MM-DD HH:MM:SS' — НЕ выполнено" >&2; exit 2; }
[ -r "$LOG" ] && [ -s "$LOG" ] || { echo "❌ журнал сторожа $LOG не читается или пуст — НЕ выполнено" >&2; exit 2; }
after=$(awk -v s="$T0" 'substr($0,2,19) >= s' "$LOG" | wc -l)
hits=$(awk -v s="$T0" -v n="'$NAME'" 'substr($0,2,19) >= s && index($0, n)' "$LOG")
if [ -n "$hits" ]; then echo "❌ сторож трогал $NAME после $T0:"; echo "$hits"; exit 1; fi
# Сторож пишет строку на каждый обход (~раз в 1–2 мин). Нет ни одной строки после T0 — не доказано, что он смотрел.
[ "$after" -gt 0 ] || { echo "❌ после $T0 в журнале сторожа нет ни одной строки — обход не доказан, НЕ выполнено (повторить через 3 мин)" >&2; exit 2; }
echo "✅ $NAME: сторож не трогал контейнер после $T0 ($after строк журнала после старта)"
