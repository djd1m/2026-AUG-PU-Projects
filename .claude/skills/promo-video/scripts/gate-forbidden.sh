#!/bin/bash
# Ворота модуля 02: таблица «Нельзя показывать → как обойдено» в SCENARIO.md полна (8 классов, у каждого способ).
# Вынесено из инлайн-цикла `for … grep` (1.2): песочница агента Claude Code отвергает составные команды — квитанция
# сквозного прогона N3, замечание 8.
#   bash .claude/skills/promo-video/scripts/gate-forbidden.sh <proj>
# Строка класса: `| цены | способ или «не применимо, потому что …» | … |` (id класса в первом столбце, можно в `…`).
# Если хоть один способ — кадрирование («кадрир…», «crop»), обязателен непустой forbidden-zones.tsv (модуль 02 п. 5).
# Коды: 0 — 8 классов, у каждого способ · 1 — дефект назван · 2 — проверка НЕ выполнена (нет SCENARIO.md, proj не тот).
set -uo pipefail
SKILL=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$SKILL/../../../.." && pwd)
REM=${PROMO_REMOTION:-$ROOT/promo/remotion}   # переопределение — только для испытания стража на копии
PROJ=${1:-}
[[ "$PROJ" =~ ^[a-z0-9-]+$ ]] || { echo "❌ proj «$PROJ» не вида ^[a-z0-9-]+$ — НЕ выполнено" >&2; exit 2; }
SC=$REM/$PROJ/SCENARIO.md
[ -s "$SC" ] || { echo "❌ нет или пуст $SC — НЕ выполнено" >&2; exit 2; }
bad=0; crop=0
for c in цены бренды фикстуры незавершённое адреса секреты числа вымышленное; do
  row=$(grep -E "^[|] *\`?$c\`? *[|]" "$SC" | head -1)
  if [ -z "$row" ]; then echo "❌ нет строки класса «$c» (первый столбец таблицы «Нельзя → как обойдено»)"; bad=1; continue; fi
  way=$(awk -F'|' '{ print $3 }' <<< "$row" | tr -d ' ')
  [ -n "$way" ] && [ "$way" != "—" ] && [ "$way" != "-" ] \
    || { echo "❌ класс «$c»: способ не назван (нужен механизм или «не применимо, потому что …»)"; bad=1; }
  grep -qiE 'кадрир|crop' <<< "$row" && crop=1
done
if [ $crop = 1 ]; then
  Z=$REM/$PROJ/forbidden-zones.tsv
  grep -qvE '^(#|[[:space:]]*$)' "$Z" 2>/dev/null \
    || { echo "❌ способ «кадрирование» назван, а в $Z нет ни одной зоны — gate-config.sh нечего проверять"; bad=1; }
fi
[ $bad = 0 ] && echo "✅ $PROJ: 8 классов «нельзя показывать», у каждого способ$([ $crop = 1 ] && echo "; зоны кадрирования объявлены")"
exit $bad
